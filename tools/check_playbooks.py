#!/usr/bin/env python3
"""
check_playbooks - validate playbook structure and generate playbooks/INDEX.md.

Usage:
    python tools/check_playbooks.py playbooks
    python tools/check_playbooks.py playbooks --index playbooks/INDEX.md
    python tools/check_playbooks.py playbooks --rules-dir ../open-yaral-detections/rules         --kql-dir ../sentinel-kql-detections/detections

--rules-dir verifies that every related_rule exists in the Google SecOps (YARA-L) library.
--kql-dir verifies that every related_kql exists in the Microsoft Sentinel (KQL) library.
Relative links between playbooks are always checked.
Standard library only (Python 3.10+).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REQUIRED_KEYS = ["id", "title", "severity", "mitre", "related_rules"]
REQUIRED_HEADINGS = [
    "## When this fires",
    "## Triage decision tree",
    "## Investigation steps",
    "## True vs false positive",
    "## Containment & response",
    "## Escalation criteria",
    "## Evidence to collect",
]
SEVERITIES = {"LOW", "MEDIUM", "HIGH", "CRITICAL"}
ID_RE = re.compile(r"^PB-[A-Z]{3}-\d{3}$")
GALLERY = "https://rizwancyberlock-svg.github.io/open-yaral-detections/#q="
KQL_REPO = "https://github.com/rizwancyberlock-svg/sentinel-kql-detections/blob/main/detections/"
LINK_RE = re.compile(r"\]\(([^)#\s]+\.md)(#[^)]*)?\)")


def front_matter(text: str) -> dict[str, str] | None:
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---", 4)
    if end == -1:
        return None
    meta = {}
    for line in text[4:end].splitlines():
        key, sep, value = line.partition(":")
        if sep:
            meta[key.strip()] = value.strip()
    return meta


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("playbooks_dir", type=Path)
    ap.add_argument("--index", type=Path, help="write a Markdown index to this path")
    ap.add_argument("--rules-dir", type=Path, help="detection library rules/ dir to cross-check related_rules")
    ap.add_argument("--kql-dir", type=Path, help="sentinel-kql-detections detections/ dir to cross-check related_kql")
    args = ap.parse_args()

    known_rules = None
    if args.rules_dir:
        known_rules = {p.stem for p in args.rules_dir.rglob("*.yaral")}
    known_kql = None
    if args.kql_dir:
        known_kql = {p.stem: p.relative_to(args.kql_dir).as_posix() for p in args.kql_dir.rglob("*.yaml")}

    errors, entries, ids = [], [], {}
    files = sorted(p for p in args.playbooks_dir.rglob("*.md") if p.name != "INDEX.md")
    for path in files:
        text = path.read_text(encoding="utf-8")
        meta = front_matter(text)
        rel = path.as_posix()
        if meta is None:
            errors.append(f"{rel}: missing front matter")
            continue
        for key in REQUIRED_KEYS:
            if not meta.get(key):
                errors.append(f"{rel}: missing front matter key '{key}'")
        if meta.get("severity") and meta["severity"] not in SEVERITIES:
            errors.append(f"{rel}: invalid severity '{meta['severity']}'")
        pid = meta.get("id", "")
        if pid and not ID_RE.match(pid):
            errors.append(f"{rel}: id '{pid}' must look like PB-ABC-001")
        if pid in ids:
            errors.append(f"{rel}: duplicate id {pid} (also {ids[pid]})")
        ids[pid] = rel
        for heading in REQUIRED_HEADINGS:
            if heading not in text:
                errors.append(f"{rel}: missing section '{heading}'")
        if "```mermaid" not in text:
            errors.append(f"{rel}: decision tree must be a mermaid diagram")
        rules = [r.strip() for r in meta.get("related_rules", "").split(",") if r.strip()]
        if known_rules is not None:
            for r in rules:
                if r not in known_rules:
                    errors.append(f"{rel}: related rule '{r}' not found in {args.rules_dir}")
        kql = [r.strip() for r in meta.get("related_kql", "").split(",") if r.strip()]
        if known_kql is not None:
            for r in kql:
                if r not in known_kql:
                    errors.append(f"{rel}: related_kql '{r}' not found in {args.kql_dir}")
        for target, _ in LINK_RE.findall(text):
            if not target.startswith("http") and not (path.parent / target).resolve().exists():
                errors.append(f"{rel}: broken link to {target}")
        entries.append((path, meta, rules, kql))

    for e in errors:
        print("ERROR  " + e)
    print(f"\n{len(files)} playbooks checked: {len(errors)} error(s)")

    if args.index:
        lines = [
            "# Playbook Index",
            "",
            "> Auto-generated by `tools/check_playbooks.py`. Do not edit by hand.",
            "",
            "| ID | Playbook | Area | Severity | ATT&CK | Google SecOps rules | Sentinel rules |",
            "|---|---|---|---|---|---|---|",
        ]
        for path, meta, rules, kql in sorted(entries, key=lambda e: e[1].get("id", "")):
            link = path.relative_to(args.index.parent).as_posix()
            area = path.parent.name
            rule_links = ", ".join(f"[`{r}`]({GALLERY}{r})" for r in rules)
            kql_links = ", ".join(f"[`{r}`]({KQL_REPO}{known_kql[r]})" if known_kql else f"`{r}`" for r in kql) or "-"
            lines.append(
                f"| {meta.get('id')} | [{meta.get('title')}]({link}) | {area} | {meta.get('severity')} | "
                f"{meta.get('mitre')} | {rule_links} | {kql_links} |"
            )
        args.index.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        print(f"wrote {args.index}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
